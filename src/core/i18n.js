/**
 * 翻译：t('home.recent')，支持 {name} 占位符插值。
 */
export function t(key, vars) {
  const table = DICT[current] || DICT[FALLBACK];
  let text = table[key];
  if (text === undefined) text = DICT[FALLBACK][key];
  if (text === undefined) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** 语言感知的日期格式化 */
export function fmtDate(value, withTime = true) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  const pad = (n) => String(n).padStart(2, '0');
  const ymd = current === 'zh'
    ? `${date.getFullYear()}年${date.getMonth() + 1}月${date.getDate()}日`
    : date.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });
  if (!withTime) return ymd;
  return `${ymd} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

/** 相对时间（“3 分钟前” / “3 min ago”） */
export function fmtRelative(value) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  const diff = Math.max(0, Date.now() - date.getTime());
  const zh = current === 'zh';
  const steps = [
    [60e3, () => (zh ? '刚刚' : 'just now')],
    [3600e3, (n) => (zh ? `${n} 分钟前` : `${n} min ago`)],
    [86400e3, (n) => (zh ? `${n} 小时前` : `${n} h ago`)],
    [30 * 86400e3, (n) => (zh ? `${n} 天前` : `${n} d ago`)],
  ];
  let lower = 0;
  for (const [span, label] of steps) {
    if (diff < span) return label(Math.max(1, Math.round(diff / Math.max(lower, 1))));
    lower = span;
  }
  return fmtDate(date, false);
}
